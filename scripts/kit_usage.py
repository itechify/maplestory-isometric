"""Write which kit @asset names the built island places: game/data/misostory/kit_assets_placed.json.

    "$B" -b MapleIsland.blend --python scripts/kit_usage.py

An asset counts as placed when a collection instance of it stands in the scene outside the asset libraries
(ENVIRONMENT_ASSETS, MONSTER_PROXIES/_MonsterLibrary, CHARACTER_PROXIES/_CharacterLibrary), or when a placed asset's
own collection instances it. The art pack's coverage check (ArtPackCoverage, run by scripts/validate_data.sh) requires
a pack model for every placed name; the catalog names the island never places are exempt. Rerun after a change that
places a new kit asset or stops placing one, and commit the file with the change.
"""

import json
import os
import sys

import bpy

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from misostory import kit  # noqa: E402

OUT = os.path.join(ROOT, "game", "data", "misostory", "kit_assets_placed.json")
LIBRARY_ROOTS = ("ENVIRONMENT_ASSETS", "_MonsterLibrary", "_CharacterLibrary")


def library_collections():
    out = set()

    def walk(c):
        out.add(c.name)
        for ch in c.children:
            walk(ch)

    for name in LIBRARY_ROOTS:
        c = bpy.data.collections.get(name)
        if c is not None:
            walk(c)
    return out


def main():
    libs = library_collections()
    placed = {}
    for ob in bpy.data.objects:
        if ob.instance_type != "COLLECTION" or ob.instance_collection is None:
            continue
        asset = ob.get("asset") or ob.instance_collection.name
        if asset not in kit.REGISTRY:
            continue
        if any(c.name in libs for c in ob.users_collection):
            continue
        if not any(ob.name in s.objects for s in bpy.data.scenes):
            continue
        placed[asset] = placed.get(asset, 0) + 1
    # Assets that placed assets instance inside their own collections.
    frontier = list(placed)
    while frontier:
        coll = bpy.data.collections.get(frontier.pop())
        if coll is None:
            continue
        for ob in coll.all_objects:
            if ob.instance_type == "COLLECTION" and ob.instance_collection is not None:
                inner = ob.get("asset") or ob.instance_collection.name
                if inner in kit.REGISTRY and inner not in placed:
                    placed[inner] = 0
                    frontier.append(inner)
    names = sorted(placed)
    by_category = {}
    for n in names:
        by_category.setdefault(kit.REGISTRY[n]["category"], []).append(n)
    doc = {
        "id": "kit_assets_placed",
        "kind": "misostory_adaptation",
        "description": ("The kit @asset names the built island places (generated by scripts/kit_usage.py from "
                        "MapleIsland.blend; do not edit). The art pack coverage check needs a pack model for each."),
        "reason": "Generated from the island build: the catalog names it never places need no art (#62).",
        "verified": False,
        "generated_by": '"$B" -b MapleIsland.blend --python scripts/kit_usage.py',
        "catalog_size": len(kit.REGISTRY),
        "placed_count": len(names),
        "names": names,
        "by_category": {k: by_category[k] for k in sorted(by_category)},
        "never_placed": sorted(n for n in kit.REGISTRY if n not in placed),
    }
    with open(OUT, "w", newline="\n") as f:
        json.dump(doc, f, indent=2)
        f.write("\n")
    print("KIT_USAGE placed %d of %d catalog names -> %s" % (len(names), len(kit.REGISTRY), OUT))


main()
