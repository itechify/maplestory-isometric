"""Export the built island's topology / map manifest.

Runs with Blender's bundled Python (no bpy needed):
"/c/Program Files/Blender Foundation/Blender 5.2/5.2/python/bin/python.exe" scripts/export_manifest.py

Inputs: src/misostory/layout.py (placement + links), docs/build_report.json (what was built),
docs/research/entities.json (classic NPC/mob data).
Outputs: docs/manifest.json and docs/MAPLE_ISLAND_MANIFEST.md (map -> exits -> destination).
"""

import importlib.util
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("layout", os.path.join(ROOT, "src", "misostory", "layout.py"))
LY = importlib.util.module_from_spec(spec)
spec.loader.exec_module(LY)

origins = LY.resolve()
report = {}
built_trails = {}
rp = os.path.join(ROOT, "docs", "build_report.json")
if os.path.exists(rp):
    full = json.load(open(rp, encoding="utf-8"))
    report = full.get("maps", {})
    built_trails = {t["trail"]: t for t in full.get("trails", [])}


def trail_m(child, ca, parent, pa, gap):
    t = built_trails.get(f"Trail_{LY.MAPS[parent]['slug']}_{pa}_to_{LY.MAPS[child]['slug']}")
    return round(t["length_m"], 1) if t else round(LY.GAPS.get((child, ca), gap), 1)
ent = {}
ep = os.path.join(ROOT, "docs", "research", "entities.json")
if os.path.exists(ep):
    ent = json.load(open(ep, encoding="utf-8")).get("per_map", {})

exits = {m: [] for m in LY.MAPS}
for child, ca, parent, pa, gap, bearing in LY.LINKS:
    one_way = (child, ca) in LY.ONE_WAY
    tm = trail_m(child, ca, parent, pa, gap)
    exits[parent].append({"portal": pa, "to_map": child, "to_portal": ca, "kind": "edge",
                          "one_way_in_classic": one_way, "trail_m": tm})
    exits[child].append({"portal": ca, "to_map": parent, "to_portal": pa, "kind": "edge",
                         "classic_arrival_only": one_way, "trail_m": tm})
for mm, pn, it, ipn in LY.DOOR_LINKS:
    exits[mm].append({"portal": pn, "to_map": it, "to_portal": ipn, "kind": "door"})
    exits[it].append({"portal": ipn, "to_map": mm, "to_portal": pn, "kind": "door"})

maps = []
for mid, m in LY.MAPS.items():
    o = origins[mid]
    gx, gy = LY.world_to_geo(o[0], o[1])
    built = report.get(str(mid), {})
    pm = ent.get(str(mid), {})
    maps.append({
        "id": mid, "name": m["name"], "slug": m["slug"], "street": m["street"], "kind": m["kind"],
        "footprint_m": [m["L"], m["D"]], "base_height_m": m["z"], "world_origin": [round(o[0], 2), round(o[1], 2)],
        "world_yaw_deg": LY.world_yaw(mid), "worldmap_frame_origin": [round(gx, 1), round(gy, 1)],
        "exits": exits[mid],
        "classic_npcs": [n.get("name") for n in pm.get("npcs", [])],
        "classic_mobs": pm.get("mobs", {}),
        "built_status": built.get("status", "not built"),
        "built_npcs": [n.get("name") for n in built.get("npcs", [])],
        "built_mobs": {s["mob"]: s["count"] for s in built.get("spawns", [])},
        "routes": [r["name"] for r in built.get("routes", [])],
        "traversal_ok": built.get("traversal", {}).get("ok"),
    })
manifest = {"island": "Maple Island (classic GMS v0.08-v0.22)", "start_map": 0,
            "primary_route": [0, 10000, 20000, 30000, 40000, 40001, 40002, 50000, 60000],
            "rainbow_street_route": [50000, 1000000, 1010000, 1020000, 1020001],
            "maps": maps}
with open(os.path.join(ROOT, "docs", "manifest.json"), "w", encoding="utf-8") as f:
    json.dump(manifest, f, indent=1)

name = {m["id"]: m["name"] for m in maps}
L = ["# Maple Island manifest (built world)", "",
     "Generated by `scripts/export_manifest.py` from `src/misostory/layout.py` and `docs/build_report.json`.",
     "Positions are meters in Blender world space. The world-map frame is the same space rotated so north is up, "
     "which is how the classic in-game world map is drawn.", "",
     "## Maps", "",
     "| ID | Name | Region | Kind | Footprint (m) | Base z | Built | Traversal | NPCs (built) | Monsters (built) |",
     "|---|---|---|---|---|---|---|---|---|---|"]
for m in maps:
    mobs = ", ".join(f"{k}×{v}" for k, v in m["built_mobs"].items())
    L.append(f"| {m['id']} | {m['name']} | {m['street']} | {m['kind']} | {m['footprint_m'][0]}×{m['footprint_m'][1]} | "
             f"{m['base_height_m']} | {m['built_status']} | {m['traversal_ok']} | {', '.join(m['built_npcs'])} | {mobs} |")
L += ["", "## Topology: map → exit → destination", ""]
for m in maps:
    L.append(f"### {m['id']} {m['name']} (`{m['slug']}`)")
    for e in m["exits"]:
        tag = ""
        if e.get("one_way_in_classic"):
            tag = " (one-way in the classic data)"
        if e.get("classic_arrival_only"):
            tag = " (arrival only in the classic data)"
        trail = f", {e['trail_m']} m trail" if e.get("trail_m") else ""
        L.append(f"- `{e['portal']}` → **{e['to_map']} {name[e['to_map']]}** `{e['to_portal']}` [{e['kind']}{trail}]{tag}")
    L.append("")
L += ["## Routes", "",
      "- Primary route: " + " → ".join(f"{i} {name[i]}" for i in manifest["primary_route"]),
      "- Rainbow Street: " + " → ".join(f"{i} {name[i]}" for i in manifest["rainbow_street_route"]),
      "- Side maps of the Field West of Amherst: 1000001, 1000002, 1000003, 1000004, 1000005, 1000006",
      "- Amherst side maps: 1010002 Amherst Townstreet → 1010004 Snail Field of Flowers; interiors 1010001, 1010003",
      "- Interiors: 20001 (from 20000), 60001 (from 60000), 1010001 and 1010003 (from 1010000)", ""]
with open(os.path.join(ROOT, "docs", "MAPLE_ISLAND_MANIFEST.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(L) + "\n")
print("MANIFEST_DONE", len(maps))
